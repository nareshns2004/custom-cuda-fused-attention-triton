"""Run every benchmark and write benchmarks/RESULTS.md. GPU only (`make bench`).

RESULTS.md is generated, never edited by hand.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import torch

from benchmarks import benchmark_add, benchmark_layernorm, benchmark_matmul
from benchmarks.common import environment, require_gpu

OUT = Path(__file__).resolve().parent / "RESULTS.md"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", choices=["add", "layernorm", "matmul"], action="append")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    require_gpu()

    selected = set(args.only or ["add", "layernorm", "matmul"])
    tables = []
    if "add" in selected:
        tables.append(benchmark_add.run())
    if "layernorm" in selected:
        tables += [benchmark_layernorm.run(dtype=d) for d in (torch.float32, torch.float16)]
    if "matmul" in selected:
        tables.append(benchmark_matmul.run())

    env = environment()
    parts = [
        "# Benchmark results",
        "",
        "Generated by `make bench` (`python -m benchmarks.run_all`). Do not edit by hand.",
        "Timings are `triton.testing.do_bench` medians (25 ms warm-up, 100 ms of repetitions).",
        "",
        "| | |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in env.items()],
        "",
        *[t.to_markdown() for t in tables],
    ]
    args.out.write_text("\n".join(parts))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
